import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const baseUrl = String(process.env.VITE_API_BASE_URL || process.env.SEATRESERVE_API_URL || '')
  .trim()
  .replace(/\/+$/, '');
const output = resolve(here, '../src/app/core/api-base.generated.ts');
await writeFile(
  output,
  `// Generated by scripts/generate-api-base.mjs. Do not edit this file manually.\nexport const BUILD_API_BASE_URL = ${JSON.stringify(baseUrl)};\n`,
  'utf8',
);
console.log(`SeatReserve API base URL: ${baseUrl || '(same origin / local proxy)'}`);
