// Runs before `ng serve` / `ng build`. Writes src/app/core/api-base.generated.ts from the
// VITE_API_BASE_URL (or API_BASE_URL) environment variable so the Angular bundle knows where the
// Render backend lives. Fails the Vercel build loudly instead of shipping an app that silently
// calls its own origin (which returns 404/401 for every /api request).
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const target = fileURLToPath(new URL('../src/app/core/api-base.generated.ts', import.meta.url));
const raw = (process.env.VITE_API_BASE_URL ?? process.env.API_BASE_URL ?? '').trim();
const value = raw.replace(/\/+$/, '').replace(/\/api$/i, '');
const onVercel = Boolean(process.env.VERCEL);

function fail(message) {
  console.error(`\n[generate-api-base] ERROR: ${message}\n`);
  process.exit(1);
}

if (value) {
  let parsed;
  try { parsed = new URL(value); } catch { fail(`VITE_API_BASE_URL "${raw}" is not a valid URL.`); }
  if (!/^https?:$/.test(parsed.protocol)) fail('VITE_API_BASE_URL must start with http:// or https://');
  if (onVercel && parsed.protocol !== 'https:') fail('On Vercel, VITE_API_BASE_URL must be https:// (browsers block http from an https page).');
} else if (onVercel) {
  fail('VITE_API_BASE_URL is not set on Vercel. Set it to your Render URL, e.g. https://seatreserve-backend.onrender.com, then redeploy.');
}

mkdirSync(dirname(target), { recursive: true });
writeFileSync(
  target,
  `// Generated by scripts/generate-api-base.mjs. Do not edit this file manually.\nexport const BUILD_API_BASE_URL = ${JSON.stringify(value)};\n`,
);
console.log(`[generate-api-base] API base URL = ${value || '(same origin / dev proxy)'}`);
