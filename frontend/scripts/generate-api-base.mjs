import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const target = resolve(here, '../src/app/core/api-base.generated.ts');
const raw = (process.env.VITE_API_BASE_URL ?? process.env.API_BASE_URL ?? '').trim();
const value = raw.replace(/\/+$/, '').replace(/\/api$/, '');
const onVercel = process.env.VERCEL === '1' || process.env.VERCEL === 'true';

if (onVercel && !value) {
  console.error('[generate-api-base] VITE_API_BASE_URL is not set. Add it in Vercel -> Settings -> Environment Variables and redeploy.');
  process.exit(1);
}
if (value && !/^https?:\/\/[^\s/]+(:\d+)?$/i.test(value)) {
  console.error(`[generate-api-base] VITE_API_BASE_URL must be an origin like https://host (got "${raw}").`);
  process.exit(1);
}

mkdirSync(dirname(target), { recursive: true });
writeFileSync(
  target,
  `// Generated by scripts/generate-api-base.mjs. Do not edit this file manually.\nexport const BUILD_API_BASE_URL = ${JSON.stringify(value)};\n`,
);
console.log(`[generate-api-base] API base = ${value || '(same origin / dev proxy)'}`);
